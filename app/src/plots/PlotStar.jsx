/** Чи вміє шар намалювати цей сюжет власною морфологією. */
export const hasMorphology = (id) => Boolean(SHAPES[id]);

/**
 * Зоря сюжету.
 *
 * plot      id сюжету з довідника; null або невідомий = порожнє кільце (3.8)
 * secondary id конкурентного сюжету: накладається привидом (3.7)
 * r         радіус ядра в пікселях, він же задає весь масштаб морфології
 * speed     множник тривалості циклів: 2 це «на 50% швидкості» для легенди
 */
export default function PlotStar({ plot, secondary, r = 10, speed = 1, className = '', style }) {
  const id = useId().replace(/:/g, '');
  const k = r / 10;
  // Поле зору. Число лишається 4.2r і після підняття амплітуд, і це рішення, а
  // не залишок: B задає габарит кнопки-вузла на карті (8.4r), і розсунувши його
  // ми розсунули б і самі зорі, тобто заплатили б за виразність однієї форми
  // щільністю всього поля. Тому амплітуди підганялись під межу.
  // Найнижча точка тепер крапля «Втрати»: 1.15r + 2.9r + радіус 0.11r = 4.16r.
  // Далі за нею йде супутник «Недосяжної орбіти» на 3.8r + 0.3r = 4.1r.
  const B = 4.2 * r;
  const Shape = SHAPES[plot];
  const Ghost = secondary && secondary !== plot ? SHAPES[secondary] : null;

  return (
    <svg
      className={`k-syu ${className}`}
      width={2 * B}
      height={2 * B}
      viewBox={`${-B} ${-B} ${2 * B} ${2 * B}`}
      style={{ '--syu-speed': speed, ...style }}
      aria-hidden="true"
      focusable="false"
    >
      {/* Привид другої сигнатури малюється ПІД основною: конкуренція це друга
          історія за першою, а не рівний із нею шар. */}
      {Ghost && (
        <g className="k-syu__ghost">
          <Ghost r={r} k={k} ghost coronaId={`${id}g`} />
        </g>
      )}
      {Shape ? <Shape r={r} k={k} coronaId={id} /> : <EmptyRing r={r} k={k} />}
    </svg>
  );
}
