// КАМЕРТОН · вкладка СЮЖЕТИ · зоряний пил.
//
// Плитка живе окремим модулем, бо пил потрібен ДВОМ сценам вкладки: полю зір і
// зум-сцені сюжету. Дві копії того самого data-URI розійшлися б на першій же
// правці щільності, і вкладка отримала б два різні неба на двох екранах одного
// шару.
//
// Плиткою і в data-URI, а не вузлами: 1px точки на прозорому тлі дешевші за
// 80 елементів у DOM і за окреме полотно з власним циклом кадрів, а різати фон
// першим при нестачі кадрів однаково доводиться саме тут.

/** Стабільний дріб з рядка: плитка має бути та сама на всіх машинах. */
function hash01(str, salt = 0) {
  let h = 2166136261 ^ salt;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return ((h >>> 0) % 10000) / 10000;
}

/* Плитка велика і рідка, а не дрібна і густа. Перша редакція мала 26 точок на
   180x120 при непрозорості 0.06-0.10: на екран це давало під півтори тисячі
   ледь помітних цяток, тобто рівну сіру шумовинку, у якій замовник фону не
   бачив узагалі. Тепер точок у плитці 24, кожна помітна поодинці, а сумарна
   світна площа навіть менша, тому правило 15% гучності від цього виграє.
   Крок дрейфу в scene.css дорівнює саме цьому розміру: інакше цикл не
   зійшовся б і кожні дві хвилини небо стрибало б. */
const W = 620;
const H = 360;

/** Розмір плитки. Той самий крок має цикл дрейфу пилу в scene.css. */
export const DUST_TILE = `${W}px ${H}px`;

export const DUST = `url("data:image/svg+xml,${encodeURIComponent(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${
    Array.from({ length: 24 }, (_, i) => {
      const x = (hash01(`d${i}`, 3) * W).toFixed(1);
      const y = (hash01(`d${i}`, 11) * H).toFixed(1);
      // Кожна пʼята точка вдвічі більша: небо з однакових цяток читається як
      // растр, а не як зорі різної віддалі.
      const s = i % 5 === 0 ? 2 : 1;
      // Стеля непрозорості тримає правило гучності поточково, а не тільки
      // сумарно: навіть найяскравіша цятка дає близько 13% яскравості ядра
      // зорі, тому пил ніколи не почне сперечатись із самими зорями.
      const o = (0.16 + hash01(`d${i}`, 23) * 0.22).toFixed(3);
      return `<rect x="${x}" y="${y}" width="${s}" height="${s}" fill="#BFEFE0" opacity="${o}"/>`;
    }).join('')
  }</svg>`
)}")`;

/**
 * Шум для дизерингу туманностей.
 *
 * Градієнт від приглушеної бірюзи до прозорого на майже чорному тлі це кілька
 * дискретних сходинок у 8 бітах, і на екрані вони читаються як концентричні
 * кола. Кола на фоні шару, де сама зоря кругла, це не атмосфера, а брак.
 * Класичне лікування це шум амплітудою в одну одиницю: сходинка розмивається
 * випадковістю і зникає, а сумарна яскравість не змінюється.
 */
export const NOISE = `url("data:image/svg+xml,${encodeURIComponent(
  '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="120">'
  + '<filter id="n"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2"/></filter>'
  + '<rect width="120" height="120" filter="url(#n)" opacity="0.5"/></svg>'
)}")`;
