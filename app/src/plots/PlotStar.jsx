/* Фрагмент свого не відлітає, але вже не разом: дрейфує від ядра і назад. */
function BetrayalByOwn({ r, k, ghost, coronaId }) {
  const ang = -35; // верх-право
  // Фрагмент винесено за кільце (2.1r проти 1.6r): своє не просто відкололось,
  // воно вже поза межею. На 1.3r він тонув у кільці і з двох кроків читався як
  // потовщення кільця, а не як окреме тіло.
  const [fx, fy] = pt(2.1 * r, ang);
  const [dx, dy] = pt(0.6 * r, ang);
  // Тріщина поперек осі відколу, у місці розриву: лінія вздовж осі читалась би
  // як привʼязь, а тут якраз розрив, а не звʼязок.
  const [cx, cy] = pt(1.2 * r, ang);
  const [hx, hy] = pt(1.0 * r, ang + 90);
  return (
    <>
      {!ghost && <Corona r={r} id={coronaId} />}
      {!ghost && <Core r={r} />}
      <g
        className={ghost ? undefined : 'k-syu__shard'}
        style={ghost ? undefined : { '--dx': `${dx.toFixed(2)}px`, '--dy': `${dy.toFixed(2)}px`, transform: `translate(${dx.toFixed(2)}px, ${dy.toFixed(2)}px)` }}
      >
        <circle cx={fx} cy={fy} r={0.45 * r} fill={ghost ? 'none' : 'var(--syuzh-star)'} stroke="var(--syuzh-dim)" strokeWidth={ghost ? 1 * k : 0} />
      </g>
      <line
        x1={cx - hx} y1={cy - hy} x2={cx + hx} y2={cy + hy}
        stroke="var(--syuzh-dim)"
        strokeWidth={1.5 * k}
        strokeDasharray={`${3 * k} ${3 * k}`}
      />
      {/* Кільце проходить МІЖ ядром і фрагментом: 1.6r менше за відступ 2.1r,
          тому фрагмент видно як тіло за межею, а не як вузол на кільці. */}
      <Ring r={r} k={k} />
    </>
  );
}

