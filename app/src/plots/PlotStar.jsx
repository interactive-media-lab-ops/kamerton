/* 3.4 Боротьба з чудовиськом/системою · лещата                      */
/* ---------------------------------------------------------------- */

/* Тиск ззовні, опір зсередини: дуги стискаються, ядро світлішає в протифазі. */
function FightMonster({ r, k, ghost, coronaId }) {
  // Хід 2.01r ... 2.89r замість 1.8r ... 2.2r: це scale 0.82 ... 1.18 від 2.45r.
  // Стиск мусить бути видно САМЕ РУХОМ, а на 0.4r ходу дуги лише дрижали.
  // Внутрішня межа не випадкова. Перша спроба ставила її на 1.84r, і на знімку
  // приймання стиснуті лещата злипались з кільцем 1.6r в одну товсту дугу: два
  // елементи різного змісту читались як один. Тепер між ними лишається 0.27r,
  // тобто просвіт, який видно і на мініатюрі.
  const R = 2.45 * r;
  return (
    <>
      {!ghost && <Corona r={r} id={coronaId} />}
      {!ghost && <Core r={r} className="k-syu__resist" />}
      <Ring r={r} k={k} />
      {/* Базовий стан це стиснуті лещата: саме він лишається, коли система
          просить спокою, бо він і є найвиразніший кадр цієї морфології. */}
      <g className={ghost ? undefined : 'k-syu__vice'} style={{ transform: 'scale(0.82)' }}>
        {[225, 45].map((mid) => (
          <path
            key={mid}
            d={arcPath(R, mid - 55, mid + 55)}
            fill="none"
            stroke="var(--syuzh-dim)"
            strokeWidth={2.8 * k}
            strokeLinecap="round"
          />
        ))}
      </g>
    </>
  );
}

