/* Супутник гасне щоразу в одній точці, не дійшовши до перигею, і починає знову. */
function ReturnFails({ r, k, ghost, coronaId }) {
  // Еліпс розтягнуто (2.9r на 1.41r проти 2.2r на 1.22r) і сплюснуто сильніше:
  // при співвідношенні 1.8 з двох кроків він читався як коло, а вся морфологія
  // тримається саме на тому, що орбіта витягнута і повернення довге.
  const rx = 2.9 * r;
  const ry = rx / 2.05;
  // Центр еліпса зсунутий, тому перигей один і той самий: ліворуч, а апогей
  // праворуч. На кільці, симетричному відносно ядра, «та сама точка згасання»
  // була б неможлива.
  const cx = 0.9 * r;
  const path = `M ${(cx + rx).toFixed(2)} 0 A ${rx.toFixed(2)} ${ry.toFixed(2)} 0 1 1 ${(cx - rx).toFixed(2)} 0 A ${rx.toFixed(2)} ${ry.toFixed(2)} 0 1 1 ${(cx + rx).toFixed(2)} 0`;
  return (
    <>
      {!ghost && <Corona r={r} id={coronaId} />}
      {!ghost && <Core r={r} />}
      <ellipse
        cx={cx} cy="0" rx={rx} ry={ry}
        fill="none" stroke="var(--syuzh-dim)" strokeWidth={1.4 * k}
      />
      {!ghost && (
        <circle
          className="k-syu__sat"
          r={0.3 * r}
          fill="var(--syuzh-star)"
          style={{ offsetPath: `path("${path}")`, offsetDistance: '30%', offsetRotate: '0deg' }}
        />
      )}
    </>
  );
}

