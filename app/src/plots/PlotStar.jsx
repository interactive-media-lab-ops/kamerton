/* З розриву знизу безперервно витікають частинки і гаснуть, не повертаючись. */
function LossDebt({ r, k, ghost, coronaId }) {
  const R = 1.6 * r;
  const N = 6;
  // Потік починається не на кільці, а біля ядра: витікає саме зоря, кільце лиш
  // не тримає. Заразом це і є та «довша течія», якої просило приймання, бо
  // подовжити її знизу нікуди: 1.15r + 3.0r це рівно 4.15r, край поля зору.
  const top = 1.15 * r;
  const fall = 2.9 * r;
  return (
    <>
      {!ghost && <Corona r={r} id={coronaId} />}
      {/* Розрив 90° знизу: кільце йде від 135° до 405° через верх. Чверть кола
          читається як пролом уже на мініатюрі, шоста частина не читалась. */}
      <path
        className="k-syu__ring"
        d={arcPath(R, 135, 405)}
        fill="none"
        stroke="var(--syuzh-dim)"
        strokeWidth={1 * k}
      />
      {!ghost && <Core r={r} />}
      {!ghost && Array.from({ length: N }, (_, i) => (
        <circle
          key={i}
          className="k-syu__drip"
          cx={(((i % 3) - 1) * 0.3 + (i % 2 ? 0.12 : -0.12)) * r}
          cy={top}
          r={1.2 * k}
          fill="var(--syuzh-star)"
          style={{
            '--fall': `${fall.toFixed(2)}px`,
            '--delay': `${i}s`,
            // Базовий кадр це не «всі краплі на півдорозі», а вся течія одразу:
            // кожна стоїть на своїй сходинці і гасне з глибиною. Саме він
            // лишається при prefers-reduced-motion, і саме він читається здалеку.
            transform: `translateY(${(fall * ((i + 0.5) / N)).toFixed(2)}px)`,
            opacity: (0.85 - i * 0.11).toFixed(2),
          }}
        />
      ))}
    </>
  );
}

