/* 3.3 Жертвопринесення · зоря, що віддає                            */
/* ---------------------------------------------------------------- */

/* Інверсія яскравості: ядро тьмяніше, корона сильніша, центр віддає себе. */
function Sacrifice({ r, k, ghost, coronaId }) {
  // Вісім напрямків рівним кроком замість пʼяти врозкид. Пʼять частинок на
  // випадкових кутах читались як сміття біля зорі, вісім на кроці 45° дають
  // впізнаваний промінь навсібіч навіть тоді, коли самих точок майже не видно.
  const dirs = [-90, -45, 0, 45, 90, 135, 180, 225];
  return (
    <>
      {/* Корона сильна, але не 1.55: на такому підсиленні вона вибілювала весь
          круг до 2.5r і зʼїдала власні промені морфології. */}
      {!ghost && <Corona r={r} id={coronaId} gain={1.35} />}
      {!ghost && <Core r={r} className="k-syu__giving" opacity={0.62} />}
      <Ring r={r} k={k} />
      {!ghost && dirs.map((deg, i) => {
        const [x0, y0] = pt(r * 1.05, deg);
        // Проліт 1.05r ... 3.3r замість 1.02r ... 2.2r: тепер частинка виходить
        // далеко за кільце, і віддачу видно як вихід назовні, а не як тремтіння
        // біля ядра. Далі не можна, за 3.5r починається край поля зору.
        const [x1, y1] = pt(r * 3.3, deg);
        // Базовий кадр розводить промені на дві висоти через одну: рівний вінець
        // читався б як зубчасте кільце, а не як течія від центра, а три висоти
        // розсипали вісімку на випадковий візерунок.
        const f = 0.4 + (i % 2) * 0.3;
        return (
          <circle
            key={deg}
            className="k-syu__ray"
            cx={x0} cy={y0} r={1.5 * k}
            fill="var(--syuzh-star)"
            style={{
              '--dx': `${(x1 - x0).toFixed(2)}px`,
              '--dy': `${(y1 - y0).toFixed(2)}px`,
              '--delay': `${(i * 0.5).toFixed(2)}s`,
              transform: `translate(${((x1 - x0) * f).toFixed(2)}px, ${((y1 - y0) * f).toFixed(2)}px)`,
              opacity: 0.75,
            }}
          />
        );
      })}
    </>
  );
}

