/* Сила формується знизу: рій підіймається конусом і торкається кільця. */
function VoiceFromBelow({ r, k, ghost }) {
  const R = 1.6 * r;
  const N = 16;
  return (
    <>
      {/* Ядро ослаблене і без корони: тут світить не центр. */}
      {!ghost && <Core r={r} opacity={0.6} />}
      <circle
        className="k-syu__ring"
        cx="0" cy="0" r={R}
        fill="none" stroke="var(--syuzh-dim)" strokeWidth={1 * k}
      />
      {/* Сплеск у момент дотику: окреме кільце поверх, бо яскравість вище
          одиниці не буває, а колір анімувати заборонено (тільки opacity).
          Штрих сплеску 2.2k проти 1k у самого кільця: основну роботу тут робить
          товщина, а не прозорість, бо на кільці 11px різниця в альфі не видно,
          а потовщення видно. Про силу сплеску див. k-syu-hit у star.css. */}
      {!ghost && (
        <circle
          className="k-syu__hit"
          cx="0" cy="0" r={R}
          fill="none" stroke="var(--syuzh-star)" strokeWidth={2.2 * k} opacity="0"
        />
      )}
      {!ghost && Array.from({ length: N }, (_, i) => {
        // Чотири хвилі по 3-4 частинки замість рівного потоку: при рівному
        // потоці кільце спалахувало б кожні 0.5 с, тобто мерехтіло б, а спека
        // просить короткий сплеск у момент дотику, а не блимання.
        const wave = i % 4;
        // Розкид рахується від номера частинки, а не від хвилі: інакше всі
        // частинки однієї хвилі йшли б однією вертикаллю, а не конусом.
        // Основа конуса розсунута до 2.65r (було 1.82r) і опущена до 3.4r: рій
        // мусить бути ширшим за саму зорю, інакше він читається як її хвіст.
        const spread = ((((i * 5) % 7) - 3) / 3) * 2.4 * r;
        const x0 = spread + (i % 2 ? 0.25 : -0.25) * r;
        const y0 = 3.4 * r;
        const x1 = x0 * 0.12;
        // Базовий кадр розводить хвилі по висоті: усі частинки на півдорозі
        // давали смугу під зорею, а не конус, що сходиться до кільця.
        const f = 0.3 + wave * 0.2;
        return (
          <circle
            key={i}
            className="k-syu__swarm"
            cx={x0} cy={y0} r={1.2 * k}
            fill="var(--syuzh-star)"
            style={{
              '--dx': `${(x1 - x0).toFixed(2)}px`,
              '--dy': `${(R - y0).toFixed(2)}px`,
              '--delay': `${(wave * 1.75 + (i % 3) * 0.12).toFixed(2)}s`,
              transform: `translate(${((x1 - x0) * f).toFixed(2)}px, ${((R - y0) * f).toFixed(2)}px)`,
              opacity: 0.75,
            }}
          />
        );
      })}
    </>
  );
}

