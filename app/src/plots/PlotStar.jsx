/**
 * Морфології шести сюжетів (розділ 3 візуальної спеки вкладки СЮЖЕТИ).
 *
 * Головне рішення вкладки: сюжет кодується ФОРМОЮ І РУХОМ зорі, а не кольором.
 * Кольору як категорії тут немає взагалі, тому і палітри сюжетів більше немає:
 * шість позицій довідника це шість морфологій, впізнаваних як обриси сузірʼїв.
 *
 * Один компонент на три масштаби: карта (r 6-16), мініатюра легенди (44px) і
 * зум-сцена (30vh). Це не економія, а вимога приймання: у легенді має стояти
 * справжній рендер тієї самої морфології, а при зумі зоря не має «телепортуватись»
 * у щось інше. Різниця тільки в r.
 *
 * ЧИСЛА. Спека задає розміри в пікселях для зорі середньої ваги. Щоб та сама
 * морфологія лишалась собою і на 8px, і на 150px, усі абсолютні числа спеки
 * помножені на k = r/10: при r = 10 виходить рівно те, що написано (частинка
 * 2.2px, падіння 30px, дрейф 6px, штрих 2.6px), а на інших розмірах пропорція
 * зберігається. Періоди циклів НЕ масштабуються: 6с лишаються 6с на будь-якому
 * розмірі, бо це час, а не геометрія.
 *
 * АМПЛІТУДА. Числа підняті проти першої редакції у 1.5-2 рази на вимогу
 * приймання: з відстані витягнутої руки шість форм мусять розрізнятись без
 * підписів. Стеля тут одна і жорстка: поле зору 4.2r (константа B). Воно
 * зашите не тільки сюди, а й у розкладку поля (PlotsScene рахує box = 4.2r*2
 * для німба і тултіпа) та в замір приймання, тому амплітуди зростали ДО межі
 * 4.2r, а не разом з нею: найдальша точка кожної морфології тепер 3.5-4.15r.
 *
 * РУХ. Кожна анімація зображає зміст свого сюжету (витікання, розкол, віддача,
 * тиск, недосяжність, тиск знизу). Декоративного руху немає. Рухаються тільки
 * transform і opacity, увесь рух живе в CSS, а базовий стан кожного рухомого
 * елемента це його НАЙВИРАЗНІШИЙ КАДР: коли prefers-reduced-motion вимикає
 * анімації, розірване кільце лишається розірваним, лещата стиснутими, супутник
 * на орбіті, а рій під зорею.
 */

const RAD = Math.PI / 180;
const pt = (r, deg) => [r * Math.cos(deg * RAD), r * Math.sin(deg * RAD)];
/** Дуга кола від кута до кута, за годинниковою в екранних координатах. */
function arcPath(R, fromDeg, toDeg) {
  const [x1, y1] = pt(R, fromDeg);
  const [x2, y2] = pt(R, toDeg);
  const large = Math.abs(toDeg - fromDeg) > 180 ? 1 : 0;
  return `M ${x1.toFixed(2)} ${y1.toFixed(2)} A ${R.toFixed(2)} ${R.toFixed(2)} 0 ${large} 1 ${x2.toFixed(2)} ${y2.toFixed(2)}`;
}

/** Спільна анатомія: орбітальне кільце радіуса 1.6r, штрих 1px. */
function Ring({ r, k, dash }) {
  return (
    <circle
      className="k-syu__ring"
      cx="0" cy="0" r={1.6 * r}
      fill="none"
      stroke="var(--syuzh-dim)"
      strokeWidth={1 * k}
      strokeDasharray={dash || undefined}
    />
  );
}

/** Корона: радіальний градієнт до 2.5r. Сила задається множником. */
function Corona({ r, id, gain = 1 }) {
  return (
    <>
      <defs>
        <radialGradient id={id}>
          <stop offset="0%" stopColor="var(--syuzh-star)" stopOpacity={0.30 * gain} />
          <stop offset="45%" stopColor="var(--syuzh-star)" stopOpacity={0.11 * gain} />
          <stop offset="100%" stopColor="var(--syuzh-star)" stopOpacity="0" />
        </radialGradient>
      </defs>
      <circle cx="0" cy="0" r={2.5 * r} fill={`url(#${id})`} />
    </>
  );
}

const Core = ({ r, className = '', opacity = 1 }) => (
  <circle className={`k-syu__core ${className}`} cx="0" cy="0" r={r} fill="var(--syuzh-star)" opacity={opacity} />
);

