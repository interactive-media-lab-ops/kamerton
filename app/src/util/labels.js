// Розведення підписів, що стоять на одній осі.
//
// Головне обмеження: підпис не можна зсувати вздовж осі. У КАМЕРТОНі x підпису
// означає саме значення (тон теми, ймовірність у приладі), тому горизонтальний
// зсув перетворив би підпис на неправду. Розводимо тільки по рядах, а те, що не
// влізло в жоден ряд, не малюємо зовсім: воно лишається доступним у tooltip.
//
// Одиниці не задані навмисно: викликач працює або в координатах viewBox, або в
// пікселях, і має передати minGap у своїх одиницях.

/**
 * @param {Array<{x:number, rank?:number}>} items підписи; менший rank
 *   розкладається першим, тобто має пріоритет на верхній ряд
 * @param {{minGap:number, rows?:number}} opts мінімальна відстань між центрами
 *   двох підписів в одному ряду і кількість доступних рядів
 * @returns {Array<number|null>} ряд для кожного підпису в порядку входу,
 *   або null, якщо підпис не влазить і має піти в tooltip
 */
export function placeLabels(items, { minGap, rows = 2 } = {}) {
  const placed = new Array(items.length).fill(null);
  const lanes = Array.from({ length: rows }, () => []);

  // Розкладаємо не зліва направо, а за пріоритетом: інакше найлівіший підпис
  // займав би верхній ряд і витісняв туди важливіший.
  const order = items
    .map((it, i) => ({ i, x: it.x, rank: it.rank ?? i }))
    .sort((a, b) => a.rank - b.rank);

  order.forEach(({ i, x }) => {
    for (let r = 0; r < rows; r += 1) {
      if (!lanes[r].some((cx) => Math.abs(cx - x) < minGap)) {
        lanes[r].push(x);
        placed[i] = r;
        return;
      }
    }
  });

  return placed;
}
